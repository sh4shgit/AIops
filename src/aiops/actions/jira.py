"""Jira integration client for AIOps Assistant.

Drafts and creates Jira issue payloads for detected anomalies and fix suggestions.
Supports dry-run mode where only the JSON payload is constructed without making
actual API calls to Jira.
"""

from __future__ import annotations

from typing import Any

import structlog

from aiops.config import get_settings
from aiops.detection.thresholds import AnomalyEvent
from aiops.reasoning.schemas import FixSuggestion

logger = structlog.get_logger()


class JiraClient:
    """Client for drafting and submitting Jira tickets."""

    def __init__(
        self,
        url: str | None = None,
        user: str | None = None,
        api_token: str | None = None,
        project_key: str | None = None,
        dry_run: bool | None = None,
    ) -> None:
        settings = get_settings()
        self.url = url or settings.jira_url
        self.user = user or settings.jira_user
        self.api_token = api_token or (settings.jira_api_token.get_secret_value() if settings.jira_api_token else "")
        self.project_key = project_key or settings.jira_project_key
        self.dry_run = dry_run if dry_run is not None else settings.dry_run

    def draft_ticket(
        self,
        suggestion: FixSuggestion,
        anomaly: AnomalyEvent,
    ) -> dict[str, Any]:
        """Generate a structured Jira issue creation payload."""
        summary = f"[AIOps Alert] {anomaly.service}: {suggestion.summary}"

        steps_formatted = "\n".join(
            f"{i+1}. {step}" for i, step in enumerate(suggestion.suggested_steps)
        )
        refs_formatted = ", ".join(suggestion.referenced_incident_ids) or "None"

        description = (
            f"h2. Anomaly Details\n"
            f"* *Service:* {anomaly.service}\n"
            f"* *Severity Band:* {anomaly.band.value}\n"
            f"* *Anomaly Score:* {anomaly.anomaly_score:.4f}\n"
            f"* *Detected At:* {anomaly.created_at.isoformat()}\n\n"
            f"h2. Root Cause Analysis\n"
            f"{suggestion.probable_cause}\n\n"
            f"h2. Suggested Remediation Steps\n"
            f"{steps_formatted}\n\n"
            f"h2. Context & Precedent\n"
            f"* *Confidence:* {suggestion.confidence * 100:.1f}%\n"
            f"* *Risk Level:* {suggestion.risk_level.value}\n"
            f"* *Similar Past Incidents:* {refs_formatted}\n\n"
            f"-----\n"
            f"_Generated by AIOps Assistant (Human In The Loop)_"
        )

        payload = {
            "fields": {
                "project": {"key": self.project_key},
                "summary": summary[:255],
                "description": description,
                "issuetype": {"name": "Incident"},
                "priority": {
                    "name": "High" if anomaly.band.value == "HIGH" else "Medium"
                },
                "labels": ["aiops-generated", anomaly.service.lower()],
            }
        }
        return payload

    async def create_ticket(self, payload: dict[str, Any]) -> dict[str, Any]:
        """Create a Jira ticket, or return the draft if dry_run is enabled."""
        if self.dry_run or not (self.url and self.user and self.api_token):
            logger.info("jira_ticket_dry_run", project=self.project_key, dry_run=self.dry_run)
            return {
                "key": f"{self.project_key}-DRAFT",
                "id": "draft-001",
                "status": "drafted",
                "payload": payload,
            }

        try:
            from jira import JIRA

            jira = JIRA(
                server=self.url,
                basic_auth=(self.user, self.api_token),
            )
            issue = jira.create_issue(fields=payload["fields"])
            logger.info("jira_ticket_created", key=issue.key)
            return {
                "key": issue.key,
                "id": str(issue.id),
                "status": "created",
                "url": f"{self.url}/browse/{issue.key}",
            }
        except Exception as e:
            logger.error("jira_ticket_failed", error=str(e))
            raise
